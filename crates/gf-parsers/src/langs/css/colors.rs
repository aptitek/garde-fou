/// Returns `true` if `ident` (case-insensitive) is one of the 148 CSS Color 4 named colors.
#[must_use]
pub fn is_css_named_color(ident: &str) -> bool {
    let lower = ident.to_ascii_lowercase();
    CSS_NAMED_COLORS.binary_search(&lower.as_str()).is_ok()
}

/// Returns `true` for CSS-wide and intrinsic color keywords permitted outside token files.
#[must_use]
pub fn is_intrinsic_color_keyword(ident: &str) -> bool {
    matches!(
        ident.to_ascii_lowercase().as_str(),
        "transparent"
            | "currentcolor"
            | "inherit"
            | "initial"
            | "unset"
            | "revert"
            | "revert-layer"
    )
}

/// Returns `true` if `fn_name` constructs a CSS Color 4 color value directly.
#[must_use]
pub fn is_direct_color_function(fn_name: &str) -> bool {
    matches!(
        fn_name.to_ascii_lowercase().as_str(),
        "rgb" | "rgba" | "hsl" | "hsla" | "hwb" | "lab" | "lch" | "oklab" | "oklch" | "color"
    )
}

/// Returns `true` if `hex` (`3`, `4`, `6`, or `8` ASCII hex digits without `#`) is a valid `#hex` color.
#[must_use]
pub fn is_valid_hex_color(hex: &str) -> bool {
    matches!(hex.len(), 3 | 4 | 6 | 8) && hex.bytes().all(|b| b.is_ascii_hexdigit())
}
